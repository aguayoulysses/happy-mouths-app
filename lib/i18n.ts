// The ops board in two languages. English is what the code says; Spanish is looked up here.
// t("Sign out") returns the Spanish line when the viewer picked Español, else the English.
// Text that carries a number uses {n}: t("{n} active", { n: 3 }). Lines the server builds
// with numbers already inside (health flags, job details) go through the PATTERNS list.

export type Lang = "en" | "es";
export const LANG_COOKIE = "hm_lang";
export const asLang = (v: string | undefined | null): Lang => (v === "es" ? "es" : "en");

export type T = {
  (s: string, vars?: Record<string, string | number>): string;
  /** Pick singular or plural by count, then fill {n}. */
  n: (count: number, one: string, many: string, vars?: Record<string, string | number>) => string;
  lang: Lang;
  /** "en-US" / "es-MX" for toLocaleDateString and friends. */
  locale: string;
};

const fill = (s: string, vars?: Record<string, string | number>) =>
  vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s;

export function makeT(lang: Lang): T {
  const look = (s: string): string => {
    if (lang !== "es") return s;
    const hit = ES[s];
    if (hit) return hit;
    for (const [re, out] of PATTERNS) {
      const m = s.match(re);
      if (m) return typeof out === "function" ? out(m) : s.replace(re, out);
    }
    return s;
  };
  const t = ((s: string, vars?: Record<string, string | number>) => fill(look(s), vars)) as T;
  t.n = (count, one, many, vars) => fill(look(count === 1 ? one : many), { n: count, ...(vars ?? {}) });
  t.lang = lang;
  t.locale = lang === "es" ? "es-MX" : "en-US";
  return t;
}

